"""Print a dated coverage and source-review queue without changing verification metadata.

Run from backend: python scripts/data_readiness.py --as-of 2026-10-25
Add --json for source URLs, reviewer/date evidence and unresolved programme IDs.
Draft packs remain usable under CLAUDE.md; coverage is distinct from source verification.
"""
from __future__ import annotations

import argparse
from datetime import date
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from campus_engine.catalogue import load_catalogue, load_funding  # noqa: E402
from scripts.validate_data import STALE_AFTER_DAYS  # noqa: E402


def source_status(source, as_of: date) -> str:
    if not source.verified:
        return "needs source review"
    if source.evidence_date > as_of:
        return "verification date after report date"
    if (as_of - source.evidence_date).days > STALE_AFTER_DAYS:
        return "needs re-check"
    return "human reviewed" if source.human_verified else "official publisher source"


def report(as_of: date) -> dict:
    universities = []
    for key, uni in sorted(load_catalogue().items()):
        universities.append({
            "id": key,
            "name": uni.name,
            "release": uni.release,
            "programmes": len(uni.programmes),
            "requirements_missing": [p.id for p in uni.programmes if p.requirements is None and p.manual_admission is None],
            "manual_admission": [p.id for p in uni.programmes if p.manual_admission is not None],
            "partial_requirements": [p.id for p in uni.programmes if p.requirements and (p.requirements.unassessed_conditions or any(c.unassessed_alternative for c in p.requirements.choices))],
            "manual_points": sum(p.requirements is not None and not (p.points_rules or uni.points_rules) for p in uni.programmes),
            "campuses": len(uni.campuses),
            "calendar_entries": len(uni.calendar),
            "calendar_years": {str(year): sum(e.start.year == year for e in uni.calendar)
                               for year in sorted({e.start.year for e in uni.calendar})},
            "support_services": len(uni.support_services),
            "support_kinds": sorted({s.kind for s in uni.support_services}),
            "campuses_without_support": [c.id for c in uni.campuses
                if not any(not s.campuses or c.id in s.campuses for s in uni.support_services)],
            "activities": len(uni.cheap_things),
            "campuses_without_activities": [c.id for c in uni.campuses
                if not any(not a.campuses or c.id in a.campuses for a in uni.cheap_things)],
            "sources": [{**s.model_dump(mode="json"), "review_status": source_status(s, as_of)} for s in uni.sources],
        })
    funding = load_funding()
    return {
        "as_of": as_of.isoformat(),
        "universities": universities,
        "funding": {"release": funding.release, "funders": len(funding.funders),
                    "sources": [{**s.model_dump(mode="json"), "review_status": source_status(s, as_of)} for s in funding.sources]},
    }


def markdown(data: dict) -> str:
    lines = ["# Data coverage and review queue", "", f"As of {data['as_of']}. Generated by `backend/scripts/data_readiness.py`.", "",
             "Dated official university, funder, government and venue sources are accepted under Rinsuna's 25 October decision. This does not claim personal review or resolve contradictory rules. Calendar counts may include different years; inspect the source before assuming 2027 coverage.", "",
             "| University | Programmes | Missing requirements | Manual points | Campuses | Calendar entries | Support | Activities | Sources needing review |",
             "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for uni in data["universities"]:
        pending = sum(s["review_status"] not in ("human reviewed", "official publisher source") for s in uni["sources"])
        lines.append(f"| {uni['id']} | {uni['programmes']} | {len(uni['requirements_missing'])} | {uni['manual_points']} | {uni['campuses']} | {uni['calendar_entries']} | {uni['support_services']} | {uni['activities']} | {pending} |")
    lines += ["", "## Calendar years and campus coverage", "",
              "An entry count does not establish a complete calendar or a complete range of support services. Central services with no campus restriction count for each campus.", "",
              "| University | Calendar entries by year | Campuses without support | Campuses without activities |",
              "|---|---|---|---|"]
    for uni in data["universities"]:
        years = ", ".join(f"{year}: {count}" for year, count in uni["calendar_years"].items()) or "None"
        lines.append(f"| {uni['id']} | {years} | {', '.join(uni['campuses_without_support']) or 'None'} | {', '.join(uni['campuses_without_activities']) or 'None'} |")
    lines += ["", "## Requirements still needing confirmation", "",
              "These entries remain unassessed. See each pack's selection note and research notes for the exact ambiguity or missing rule.", ""]
    for uni in data["universities"]:
        if uni["requirements_missing"]:
            lines.append(f"- **{uni['id']}**: " + ", ".join(f"`{pid}`" for pid in uni["requirements_missing"]))
    lines += ["", "## Partially assessed requirements", "",
              "Known requirements are checked; other published alternatives or admission conditions still need clarification. These are not fully resolved records.", ""]
    for uni in data["universities"]:
        if uni["partial_requirements"]:
            lines.append(f"- **{uni['id']}**: " + ", ".join(f"`{pid}`" for pid in uni["partial_requirements"]))
    lines += ["", "## Published routes requiring university assessment", "",
              "These are documented prior-qualification or faculty-placement routes, not automated school-mark matches. They are separate from missing requirements; no eligibility is claimed.", ""]
    for uni in data["universities"]:
        if uni["manual_admission"]:
            lines.append(f"- **{uni['id']}**: " + ", ".join(f"`{pid}`" for pid in uni["manual_admission"]))
    funding = data["funding"]
    pending = sum(s["review_status"] not in ("human reviewed", "official publisher source") for s in funding["sources"])
    lines += ["", f"Funding: {funding['funders']} funders; release={str(funding['release']).lower()}; {pending} sources need source review or re-check.", "",
              "Generate `--json` for source URLs, retrieval dates and verification basis. Official-source acceptance preserves existing personal review metadata; retrieval dates have not been converted to human verification dates.", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--as-of", required=True, type=date.fromisoformat)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    data = report(args.as_of)
    print(json.dumps(data, ensure_ascii=False, indent=2) if args.json else markdown(data))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
